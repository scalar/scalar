describe('postman-dynamic-variables', () => {
  it.each(dynamicVariables)('resolves %s with the patched Faker dependency', (name) => {
    const template = `{{${name}}}`
    const result = Property.replaceSubstitutions(template, [])

    expect(typeof result).toBe('string')
    expect(result).not.toBe(template)
    expect(result).not.toBe('')
  })

  it('preserves the four-digit credit card mask', () => {
    expect(Property.replaceSubstitutions('{{$randomCreditCardMask}}', [])).toMatch(/^\d{4}$/)
  })

  it('generates a company suffix rather than a company name', () => {
    expect(Property.replaceSubstitutions('{{$randomCompanySuffix}}', [])).toMatch(/^(Group|Inc|LLC|and Sons)$/)
  })
})
